#Pide dos números enteros y muestra los tres resultados: suma, resta y multiplicación.
print("Elige 2 numeros enteros y anotalos a continuacion")
num1=int(input("Escriba el primer numero:   "))
num2=int(input("Escriba el segundo numero:   "))
print(f"{num1} + {num2} = {num1 + num2}")
print(f"{num1} - {num2} = {num1 - num2}")
print(f"{num1} * {num2} = {num1 * num2}")